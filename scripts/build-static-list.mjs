// Regenerates the crawler-readable model list in catalog.html from the PRODUCTS array.
// Run after editing PRODUCTS: node scripts/build-static-list.mjs
import { readFileSync, writeFileSync } from 'fs';

const file = new URL('../catalog.html', import.meta.url);
let html = readFileSync(file, 'utf-8');

const m = html.match(/const PRODUCTS = (\[[\s\S]*?\n\]);/);
if (!m) throw new Error('PRODUCTS array not found');
const PRODUCTS = new Function(`return ${m[1]}`)();

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function table(title, items) {
  const rows = items.map(p => `<tr><td>${esc(p.brand)}</td><td>${esc(p.name)}</td><td>${esc(p.cc)}</td><td>${esc(p.spec)}</td></tr>`).join('\n');
  return `<h3>${esc(title)} (${items.length} models)</h3>
<table class="static-list">
<thead><tr><th>Brand</th><th>Model</th><th>${title === 'Used Cars' ? 'Body type' : 'Engine'}</th><th>Specification</th></tr></thead>
<tbody>
${rows}
</tbody>
</table>`;
}

const moto = PRODUCTS.filter(p => p.category === 'moto');
const car = PRODUCTS.filter(p => p.category === 'car');

const block = `<!-- STATIC-LIST:START (generated by scripts/build-static-list.mjs, do not edit by hand) -->
<section class="static-list-section" id="model-list">
<style>
.static-list-section{max-width:1100px;margin:40px auto;padding:0 20px;color:var(--gray-text,#444);font-size:.9rem}
.static-list-section h2{font-size:1.3rem;margin-bottom:6px;color:var(--navy,#1A1A2E)}
.static-list-section h3{font-size:1.05rem;margin:22px 0 8px;color:var(--navy,#1A1A2E)}
.static-list{width:100%;border-collapse:collapse}
.static-list th,.static-list td{border-bottom:1px solid #e3e3e3;padding:6px 8px;text-align:left}
.static-list th{background:#f5f5f5;font-weight:600}
</style>
<h2>Full model list: ${moto.length} used motorcycles and ${car.length} used cars for export</h2>
<p>Luckwell CO., LTD (Kaohsiung, Taiwan) exports used motorcycles and cars wholesale. Motorcycle MOQ: 50 units per 20FT container or 125 units per 40HQ container. Car MOQ: 5 units per 40HQ container. Indicative FOB Kaohsiung price: motorcycles US$185&ndash;900 per unit, cars US$1,880&ndash;4,680 per unit, depending on model, year and condition grade. Request a quotation and current stock list by WhatsApp using the inquiry list above.</p>
${table('Used Motorcycles', moto)}
${table('Used Cars', car)}
</section>
<!-- STATIC-LIST:END -->`;

const re = /<!-- STATIC-LIST:START[\s\S]*?<!-- STATIC-LIST:END -->/;
if (re.test(html)) html = html.replace(re, () => block);
else html = html.replace('<!-- MOBILE FLOAT -->', () => `${block}\n\n<!-- MOBILE FLOAT -->`);

writeFileSync(file, html);
console.log(`static list: ${moto.length} motorcycles, ${car.length} cars`);
